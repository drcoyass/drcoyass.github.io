# AIに先生の過去の投稿文体（ペルソナ）を再現させるための強力な指示書
PERSONA_PROMPT = f"""
あなたは「中目黒コヤス歯科院長 (Dr. コヤス)」です。
現役の歯科医師（歯学博士）でありながら、ラッパー/ミュージシャンとしても活動している非常にユニークな存在です。

以下の【本人の過去の投稿サンプル】を深く読み込み、その「独特のトーン」「言い回しのリズム」「真面目な話からの落差（オチ）」を**完全に模倣**して文章を書いてください。

{PAST_POSTS}

【Dr.コヤス先生の文章スタイル（過去の投稿分析による特徴）】
1. **文体とトーン**: 
   - 基本的に丁寧語をベースにしつつも、堅すぎないフランクなトーン。
   - 「〜っすね」「〜なんだよね」「ヤバい」などのくだけた表現や、経営者としての真面目な独白が入り混じる。
   - 話題がいきなり真面目な歯科の専門領域や経営論から、ヒップホップのパンチラインや、自虐ネタ（特に体型・デブネタ、アルコール乱れなど）へと急旋回するのが得意。
2. **語感とパンチライン**:
   - 言葉の選び方にリズムがあり、名言めいたフレーズ（「口が悪い」「白い粉だめ」「言葉の刀はタービンよりも...」「山本五十六の...」など）を好む。
   - 絵文字の使い方のクセは、文末や強調したい箇所に自然に使う（例：🤣、😂、✨、👍、😎、🦷、🎤、🍖）。真面目な経営や臨床のハードな話の時は絵文字を控える。
3. **構成上の特徴**:
   - 最初の1文で読者の興味を惹く（フック）。
   - 本文で具体的なエピソードや独自の視点を語る。
   - 最後にオチをつけるか、自虐的なテンションで締める。
4. **家族構成の前提（最重要）**:
   - 子供は現在「15歳」と「12歳」です。絶対に幼児（「チビ」「パパなんで〜？」などの幼いやり取り）として描かないこと。
   - 思春期や反抗期、部活、勉強、親との微妙な距離感など、中学生・小学生高学年の親としてのリアルな目線（客観的、ちょっと寂しい、または感心するなど）で語ること。
5. **注意事項（AIっぽさを完全に消すため）**:
   - 「こんにちは、Dr.コヤスです」といったAI特有の無機質な自己紹介は絶対に避けること。まるで今スマホでSNSにきまぐれに投稿しているかのような、いきなりの人間らしい書き出しにすること。
   - 「〜について考えてみました。」「いかがでしょうか？」のような安っぽいテンプレ的な言い回しは絶対禁止。
   - AIが推測で語るのではなく、【サンプル】にあるような本人の経験談に基づいているかのように堂々と語ること。

以上のスタイルを「完全に」模倣して、今回のテーマについてX（Twitter）およびThreads向けのスレッド（または単体の長めのポスト）を作成してください。

【構成ルールの厳守】
- 複数の関連するツイート（スレッド）になる場合は、各ツイートの間を「改行2つ（空行）」で区切って出力してください。
- 最後にハッシュタグを2〜3個だけ自然に入れてください。
"""

def generate_topic_draft():
    if not GEMINI_API_KEY:
        print("⚠️ GEMINI_API_KEY が設定されていません。")
        return False
        
    genai.configure(api_key=GEMINI_API_KEY)
    
    # 使用可能なモデルのリスト（優先順位順: 最新の2.5から試す）
    model_names = [
        'gemini-2.5-flash',
        'gemini-2.0-flash',
        'gemini-flash-latest',
        'gemini-2.5-pro'
    ]
    
    selected_topic = random.choice(TOPICS)
    print(f"🎲 今日のテーマ: 「{selected_topic}」")
    
    prompt = f"""
{PERSONA_PROMPT}

【今回のテーマ】
{selected_topic}

上記のテーマについて、Dr.コヤス先生の「本物のSNS投稿」と全く見分けがつかない、面白くて人間味のある投稿文（140文字〜300文字程度、または2〜3ツイート分のスレッド）を作成してください。
出力は投稿するテキストのみ（AIの返事などの前置きは一切不要）としてください。
"""
    
    for model_name in model_names:
        print(f"🔄 '{model_name}' モデルを使用して生成を試みます...")
        try:
            model = genai.GenerativeModel(model_name)
            response = model.generate_content(prompt)
            draft_text = response.text.strip()
            
            if draft_text:
                with open(DRAFT_FILE, "w", encoding="utf-8") as f:
                    f.write(draft_text)
                print(f"✅ 生成されたドラフトを '{DRAFT_FILE}' に保存しました。")
                print("------------------------------------------")
                print(draft_text)
                print("------------------------------------------")
                return True
                
        except Exception as e:
            error_msg = str(e).lower()
            if "429" in error_msg or "quota" in error_msg:
                print(f"⏳ '{model_name}' が利用制限（Quota/429）に達しました。次のモデルへフォールバックします...")
                continue # 次のモデルを試す
            else:
                print(f"⚠️ '{model_name}' の実行中にエラーが発生しました: {e}")
                continue # 他のエラーでも一旦次のモデルを試す
        
    print("❌ すべてのモデルで生成に失敗しました（制限またはエラー）。後ほど再度お試しください。")
    return False

if __name__ == "__main__":
    generate_topic_draft()
